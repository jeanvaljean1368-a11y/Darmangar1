// Get neighborhoods for a city (falls back to generic zones if city not found)
export function getNeighborhoodsForCity(city: string): string[] {
  if (!city) return []
  if (CITY_NEIGHBORHOODS[city]) return CITY_NEIGHBORHOODS[city]
  // Generic fallback for cities without specific data
  return [
    'مرکز شهر',
    'شمال شهر',
    'جنوب شهر',
    'شرق شهر',
    'غرب شهر',
  ]
}

// Parse served neighborhoods JSON array
export function parseServedNeighborhoods(json: string | null | undefined): string[] {
  if (!json) return []
  try {
    const arr = JSON.parse(json)
    return Array.isArray(arr) ? arr : []
  } catch {
    return []
  }
}

// Serialize neighborhoods array to JSON for storage
export function serializeServedNeighborhoods(arr: string[]): string {
  return JSON.stringify(arr)
}

